#!/usr/bin/env bash
# Regenerate docs/schema.sql from the Alembic migrations (offline: no database connection needed).
set -euo pipefail
cd "$(dirname "$0")/../backend"
{
  echo "-- Atelier V1 schema. GENERATED by scripts/generate-schema-sql.sh (alembic upgrade head --sql)."
  echo "-- Alembic (backend/migrations) is the source of truth; regenerate this file after any migration."
  echo "-- Requires PostgreSQL 13+. Apply to an EMPTY database:  psql -d atelier_dev -f docs/schema.sql"
  echo
  DATABASE_URL="${DATABASE_URL:-postgresql+psycopg://offline:offline@localhost/offline}" \
    ../.venv/bin/alembic upgrade head --sql 2>/dev/null
} > ../docs/schema.sql
echo "docs/schema.sql regenerated"
